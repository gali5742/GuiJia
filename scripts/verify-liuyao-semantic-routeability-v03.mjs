import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(root, relative));
const readJson = (relative) => JSON.parse(read(relative).toString('utf8'));
const sha256 = (relative) => createHash('sha256').update(read(relative)).digest('hex');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const artifactPath = 'data/liuyao-semantic-routeability-v0.3.json';
const lockPath = 'data/liuyao-semantic-routeability-v0.3.lock.json';
const artifact = readJson(artifactPath);
const lock = readJson(lockPath);
assert(artifact.version === '0.3' && artifact.status === 'frozen' && artifact.scope === 'liuyao_semantic_routeability_v03', 'Routeability v0.3 artifact contract mismatch');
assert(artifact.baseModel?.version === '0.2' && artifact.baseModel?.weightsReusedUnchanged === true, 'v0.3 must reuse frozen v0.2 weights unchanged');
assert(artifact.baseModel.sha256 === sha256(artifact.baseModel.path), 'v0.3 base model hash drift');
assert(artifact.encoder?.revision === '75c43b069aac4d136ba6bc1122f995fedcfd2781' && artifact.encoder?.vectorSize === 512, 'v0.3 encoder contract drift');
assert(Number.isFinite(artifact.calibration?.threshold), 'v0.3 threshold missing');
assert(artifact.calibration?.total === 223 && artifact.calibration?.byLabel?.route_known === 88 && artifact.calibration?.byLabel?.non_route === 135, 'v0.3 calibration counts drift');
assert(artifact.calibration.falseActivation <= 0.05 + 1e-12, `v0.3 overall false activation ${artifact.calibration.falseActivation} > 0.05`);
assert(artifact.calibration.maxSubtypeFalseActivation <= 0.05 + 1e-12, `v0.3 subtype false activation ${artifact.calibration.maxSubtypeFalseActivation} > 0.05`);
for (const subtype of ['outside_current_22','route_unresolved','near_domain_not_current_route']) assert(artifact.calibration.bySubtype?.[subtype]?.falseActivation <= 0.05 + 1e-12, `${subtype} false activation cap violated`);
assert(artifact.calibration.byPath?.support_arbitration?.n === 44 && artifact.calibration.byPath?.fallback_head?.n === 44, 'v0.3 calibration path counts drift');
for (const source of artifact.sources || []) assert(source.sha256 === sha256(source.path), `v0.3 source drift: ${source.path}`);
assert(lock.version === '0.3-lock' && lock.status === 'locked', 'v0.3 lock contract mismatch');
assert(lock.artifactPath === artifactPath && lock.artifactSha256 === sha256(artifactPath), 'v0.3 artifact SHA lock mismatch');
assert(lock.baseModelSha256 === artifact.baseModel.sha256, 'v0.3 base model lock mismatch');
assert(lock.calibrationDataSha256 === sha256('data/liuyao-semantic-routeability-v0.3-calibration.json'), 'v0.3 calibration data lock mismatch');
assert(lock.threshold === artifact.calibration.threshold, 'v0.3 threshold lock mismatch');
console.log('LiuYao Semantic Routeability v0.3 frozen artifact verified.');
console.log(`- threshold: ${artifact.calibration.threshold}`);
console.log(`- calibration known recall: ${artifact.calibration.knownRecall}`);
console.log(`- calibration false activation: ${artifact.calibration.falseActivation}`);
console.log(`- max subtype false activation: ${artifact.calibration.maxSubtypeFalseActivation}`);
console.log(`- support/fallback recall: ${artifact.calibration.byPath.support_arbitration.recall} / ${artifact.calibration.byPath.fallback_head.recall}`);
console.log(`- artifact SHA-256: ${lock.artifactSha256}`);
