import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const readJson=(r)=>JSON.parse(fs.readFileSync(path.join(root,r),'utf8'));
const sha=(r)=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,r))).digest('hex');
const assert=(c,m)=>{if(!c)throw new Error(m);};
const artifactPath='data/liuyao-semantic-routeability-v0.4.json';
const lockPath='data/liuyao-semantic-routeability-v0.4.lock.json';
const executionPath='data/liuyao-semantic-embedding-execution-contract-v0.1.json';
assert(fs.existsSync(path.join(root,artifactPath))&&fs.existsSync(path.join(root,lockPath)),'corrected Routeability artifact/lock missing');
const a=readJson(artifactPath), l=readJson(lockPath), e=readJson(executionPath);
assert(a.version==='0.4'&&a.status==='frozen_representation_corrected'&&a.scope==='liuyao_semantic_routeability_v04','artifact contract drift');
assert(l.status==='locked_representation_corrected'&&l.artifactSha256===sha(artifactPath),'lock/SHA drift');
assert(l.executionContractSha256===sha(executionPath)&&e.canonicalInvocation?.textsPerEncoderCall===1,'execution contract drift');
assert(a.representationCorrection?.textsPerEncoderCall===1&&a.representationCorrection?.freshGeneralizationClaim===false,'representation metadata drift');
assert(a.representationCorrection?.legacyModel==='data/liuyao-semantic-routeability-v0.2.json'&&a.representationCorrection?.legacyModelMutated===false,'legacy provenance drift');
assert(a.encoder?.textsPerEncoderCall===1&&a.encoder?.vectorSize===512,'encoder contract drift');
assert(Array.isArray(a.model?.weights)&&a.model.weights.length===512&&a.model.weights.every(Number.isFinite)&&Number.isFinite(a.model.bias),'model shape/value drift');
assert(Number.isFinite(a.calibration?.threshold)&&a.calibration.threshold===l.threshold,'threshold drift');
assert(a.calibration?.evidenceStatus==='representation_correction_reprocessed_not_fresh','calibration evidence status drift');
assert(a.calibration.falseActivation<=0.05+1e-12,'overall false activation unsafe');
assert(a.calibration.maxSubtypeFalseActivation<=0.05+1e-12,'subtype false activation unsafe');
for(const subtype of ['outside_current_22','route_unresolved','near_domain_not_current_route']) assert(a.calibration.bySubtype?.[subtype]?.falseActivation<=0.05+1e-12,`unsafe subtype ${subtype}`);
const trainingSources=(a.sources||[]).filter(x=>x.role?.includes('train')).map(x=>x.path);
for(const forbidden of ['sealed-blind','independent','development-report']) assert(!trainingSources.some(p=>p.includes(forbidden)),`forbidden training source ${forbidden}`);
assert((a.sources||[]).some(x=>x.role==='representation_correction_calibration_not_fresh_evidence'),'calibration source role missing');
const runtime=fs.readFileSync(path.join(root,'js/liuyao-semantic-routeability-frozen-v04.js'),'utf8');
assert(!/\.train\s*\(/.test(runtime)&&!/calibrat\w*\s*\(/.test(runtime),'runtime must load/score only');
console.log('LiuYao corrected Routeability v0.4 verified.');
console.log(`- threshold=${a.calibration.threshold}`);
console.log(`- known recall=${a.calibration.knownRecall}`);
console.log(`- false activation=${a.calibration.falseActivation}; max subtype=${a.calibration.maxSubtypeFalseActivation}`);
console.log(`- support recall=${a.calibration.byPath?.support_arbitration?.recall}; fallback recall=${a.calibration.byPath?.fallback_head?.recall}`);
console.log(`- artifact SHA-256=${l.artifactSha256}`);
