import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(root, relative));
const readJson = (relative) => JSON.parse(read(relative).toString('utf8'));
const sha256 = (relative) => createHash('sha256').update(read(relative)).digest('hex');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const candidatePath = 'data/liuyao-semantic-decision-stack-v0.13-candidate-v0.1.json';
const lockPath = 'data/liuyao-semantic-decision-stack-v0.13-candidate-v0.1.lock.json';
const candidate = readJson(candidatePath);
const lock = readJson(lockPath);
assert(candidate.version === '0.13-candidate-v0.1' && candidate.status === 'frozen_candidate' && candidate.scope === 'liuyao_semantic_decision_stack_v0.13', 'candidate contract mismatch');
assert(candidate.modernSemanticOnly === true, 'candidate must remain modern-semantic only');
assert(candidate.policyGate === 'v0.1' && candidate.evidence === 'v0.2' && candidate.arbitration === 'v0.12' && candidate.compatibility === 'v0.2' && candidate.selection === 'v0.2', 'candidate semantic version drift');
assert(candidate.routeability?.version === 'v0.3' && Number.isFinite(candidate.routeability.threshold), 'candidate routeability missing');
assert(candidate.scopeHardVeto === 0.4196, 'candidate hard veto drift');
assert(candidate.evaluationPolicy?.independentEvalMustBeFreshAfterThisLock === true && candidate.evaluationPolicy?.independentEvalMayNotTrainOrCalibrateThisCandidate === true, 'independent eval discipline missing');
assert(candidate.evaluationPolicy?.futureBlindMustBeFreshAfterCandidateLock === true && candidate.evaluationPolicy?.noSameVersionRetuneAfterBlind === true, 'blind discipline missing');
for (const source of candidate.sources || []) assert(source.sha256 === sha256(source.path), `candidate source drift: ${source.path}`);
const routeabilityLock = readJson('data/liuyao-semantic-routeability-v0.3.lock.json');
const frozenLock = readJson('data/liuyao-semantic-frozen-dependencies-v0.1.lock.json');
assert(candidate.routeability.artifactSha256 === routeabilityLock.artifactSha256, 'candidate Routeability artifact drift');
assert(candidate.router.dependencyArtifactSha256 === frozenLock.artifactSha256, 'candidate frozen dependency artifact drift');
assert(lock.version === '0.13-candidate-v0.1-lock' && lock.status === 'locked', 'candidate lock contract mismatch');
assert(lock.candidatePath === candidatePath && lock.candidateSha256 === sha256(candidatePath), 'candidate SHA lock mismatch');
assert(lock.routeabilityArtifactSha256 === routeabilityLock.artifactSha256, 'candidate lock Routeability SHA drift');
assert(lock.frozenDependencyArtifactSha256 === frozenLock.artifactSha256, 'candidate lock frozen dependency SHA drift');
const modernSources = candidate.sources.filter((source) => source.path.startsWith('js/liuyao-semantic-route-') || source.path.includes('routeability-v03'));
const sourceText = modernSources.map((source) => read(source.path).toString('utf8')).join('\n');
for (const term of ['妻财','官鬼','父母爻','兄弟爻','子孙爻','世爻','应爻','用神']) assert(!sourceText.includes(term), `traditional field leaked into frozen modern candidate: ${term}`);
console.log('LiuYao Semantic Decision Stack v0.13 candidate lock verified.');
console.log(`- candidate SHA-256: ${lock.candidateSha256}`);
console.log(`- Routeability v0.3: threshold=${candidate.routeability.threshold}`);
console.log(`- frozen dependency artifact: ${candidate.router.dependencyArtifactSha256}`);
console.log(`- locked source/artifact files: ${candidate.sources.length}`);
