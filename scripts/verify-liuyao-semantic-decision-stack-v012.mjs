import './verify-liuyao-semantic-decision-stack-v012-evidence.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const fail=m=>{throw new Error(m)};const assert=(c,m)=>{if(!c)fail(m)};
const stack=read('js/liuyao-semantic-decision-stack-v012.js');
const evidence=read('js/liuyao-semantic-route-evidence-v01.js');
const arbitration=read('js/liuyao-semantic-route-arbitration-v010.js');
const identity=read('js/liuyao-semantic-route-identity-v02.js');
assert(stack.includes("VERSION='0.12-development'"),'v0.12 version marker missing');
assert(stack.includes('semanticDecisionStackV011 as frozenCandidate'),'v0.12 must reuse frozen v0.11 candidate preparation');
assert(stack.includes("liuyaoSemanticRouteEvidenceV01"),'v0.12 shared evidence dependency missing');
assert(stack.includes("liuyaoSemanticRouteArbitrationV010"),'v0.12 arbitration v0.10 dependency missing');
assert(stack.includes("liuyaoSemanticRouteIdentityV02"),'v0.12 identity v0.2 dependency missing');
assert(stack.includes("arbitration?.strength==='strong'"),'only strong arbitration may establish route');
assert(stack.includes("arbitration?.strength==='support'&&arbitration.routeId===head.top1.id"),'support arbitration must only reinforce matching head candidate');
assert(stack.includes("semanticDecisionStackV011 as frozenCandidate")&&stack.includes('scopeHardVetoCutoff=candidateTraining.scope.threshold'),'frozen v0.11 Scope hard-veto policy must be reused');
assert(stack.includes('decideV011')&&stack.includes('decideV012'),'same-corpus A/B decision paths missing');
assert(!stack.includes('sealed-blind-v0.1.json'),'v0.12 runtime must not read v0.11 sealed Blind');
assert(evidence.includes("currentTargets")&&evidence.includes("background"),'shared evidence must distinguish current target and background');
for(const group of ['domains','events','objects','directions','relations','goals'])assert(evidence.includes(group),`shared evidence group missing: ${group}`);
assert(arbitration.includes("current-target-over-background")&&arbitration.includes("current-target-over-position-background"),'arbitration target/background precedence missing');
assert(arbitration.includes("strength")&&arbitration.includes("'strong'")&&arbitration.includes("'support'"),'arbitration evidence strength contract missing');
assert(identity.includes('liuyaoSemanticRouteEvidenceV01'),'Identity v0.2 must consume shared evidence');
assert(!/(妻财|官鬼|父母爻|兄弟爻|子孙爻|世爻|应爻|用神)/.test(evidence+arbitration+identity),'traditional LiuYao semantics leaked into modern route decision layer');
console.log('LiuYao Semantic Decision Stack v0.12 runtime contract verified.');
console.log('- frozen v0.11 candidate preparation / Scope hard-veto reused');
console.log('- shared Route Semantic Evidence v0.1 feeds Arbitration v0.10 and Identity v0.2');
console.log('- current-target > background precedence is explicit');
console.log('- only strong arbitration may override; support evidence cannot override head');
console.log('- v0.11 sealed Blind is not read by v0.12 runtime');
